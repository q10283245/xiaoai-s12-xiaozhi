#!/usr/bin/env python3
"""Generate original, quiet integer-waveform cues; no recordings or TTS input.

All arithmetic is integer, so identical recipes produce identical PCM on every
Python platform. These cues intentionally do not reproduce Xiaomi recordings.
The generated declarations retain the existing client's C interface.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
RATE = 16000
PEAK = 2400
FADE_MS = 10
RECIPES = {
    "followup": [(1040, 100)],
    "volume": [(660, 70)],
    "button": [(880, 60)],
    "farewell0": [(880, 80), (0, 20), (660, 110)],
    "farewell1": [(1040, 70), (0, 15), (780, 70), (0, 15), (520, 100)],
    "farewell2": [(780, 90), (0, 20), (520, 130)],
}
PROVENANCE = "Original integer triangle-wave synthesis; no vendor audio or TTS."


def pcm(recipe: list[tuple[int, int]]) -> bytes:
    result = bytearray()
    fade = RATE * FADE_MS // 1000
    for hz, milliseconds in recipe:
        frames = RATE * milliseconds // 1000
        for index in range(frames):
            phase = index * hz % RATE if hz else 0
            if not hz:
                wave = 0
            elif phase < RATE // 4:
                wave = 4 * phase
            elif phase < 3 * RATE // 4:
                wave = 2 * RATE - 4 * phase
            else:
                wave = 4 * phase - 4 * RATE
            envelope = min(index, frames - index - 1, fade)
            value = wave * PEAK * envelope // (RATE * fade)
            result.extend(struct.pack("<h", value))
    return bytes(result)


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def recipe_digest(name: str) -> str:
    recipe = {"version": 1, "rate": RATE, "peak": PEAK, "fade_ms": FADE_MS,
              "wave": "integer-triangle", "notes": RECIPES[name]}
    return digest(json.dumps(recipe, separators=(",", ":"), sort_keys=True).encode())


def array(name: str, data: bytes, ctype: str = "unsigned char") -> list[str]:
    lines = [f"_Alignas(2) static const {ctype} {name}[] = {{"]
    for offset in range(0, len(data), 16):
        lines.append("    " + ",".join(f"0x{x:02x}" for x in data[offset:offset + 16]) + ",")
    return lines + ["};"]


def preamble(guard: str) -> list[str]:
    return ["/* Generated by scripts/generate_prompts.py; do not edit PCM bytes.",
            " * " + PROVENANCE, " * Mono S16_LE, 16000 Hz; peak <=2400/32768; 10 ms fades.",
            " * SPDX-License-Identifier: MIT", " */", f"#ifndef {guard}", f"#define {guard}"]


def outputs() -> dict[str, bytes]:
    rendered: dict[str, bytes] = {}
    data = pcm(RECIPES["followup"])
    lines = preamble("S12_FOLLOWUP_READY_PCM_H") + [
        "#define S12_FOLLOWUP_PROMPT_RATE 16000u",
        "#define S12_FOLLOWUP_READY_MILLISECONDS 100u",
        "#define S12_FOLLOWUP_READY_FADE_MILLISECONDS 10u",
        f'#define S12_FOLLOWUP_PROMPT_PCM_SHA256 "{digest(data)}"',
    ] + array("s12_followup_prompt_pcm", data) + [
        "#define S12_FOLLOWUP_PROMPT_PCM_BYTES (sizeof(s12_followup_prompt_pcm))",
        "#define S12_FOLLOWUP_PROMPT_SAMPLES (S12_FOLLOWUP_PROMPT_PCM_BYTES / 2u)", "#endif", ""]
    rendered["followup_ready_pcm.h"] = "\n".join(lines).encode()
    lines = preamble("S12_UI_FEEDBACK_PCM_H") + ["#define S12_UI_FEEDBACK_RATE 16000u"]
    for name in ("volume", "button"):
        data = pcm(RECIPES[name])
        prefix = "S12_" + name.upper() + "_PROMPT"
        lines += [f'#define {prefix}_SOURCE_SHA256 "{recipe_digest(name)}"',
                  f'#define {prefix}_PCM_SHA256 "{digest(data)}"']
        lines += array("s12_" + name + "_prompt_pcm", data)
        lines += [f"#define {prefix}_PCM_BYTES (sizeof(s12_{name}_prompt_pcm))",
                  f"#define {prefix}_SAMPLES ({prefix}_PCM_BYTES / 2u)"]
    rendered["ui_feedback_pcm.h"] = "\n".join(lines + ["#endif", ""]).encode()
    lines = preamble("S12_FAREWELL_PROMPT_PCM_H") + [
        "#include <stdint.h>", "#define S12_FAREWELL_PROMPT_RATE 16000u",
        "struct s12_farewell_clip { const uint8_t *pcm; unsigned bytes; };"]
    for index in range(3):
        lines += array(f"s12_farewell_prompt_pcm_{index}", pcm(RECIPES[f"farewell{index}"]), "uint8_t")
    lines += ["static const struct s12_farewell_clip s12_farewell_clips[] = {"]
    for index in range(3):
        name = f"s12_farewell_prompt_pcm_{index}"
        lines += [f"    {{ {name}, sizeof({name}) }},"]
    lines += ["};", "#define S12_FAREWELL_PROMPT_COUNT ((unsigned)(sizeof(s12_farewell_clips) / sizeof(s12_farewell_clips[0])))",
              "#endif", ""]
    rendered["farewell_prompt_pcm.h"] = "\n".join(lines).encode()
    return rendered


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare without writing")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "device")
    args = parser.parse_args()
    rendered = outputs()
    if args.check:
        bad = [name for name, data in rendered.items()
               if not (args.output_dir / name).is_file() or (args.output_dir / name).read_bytes() != data]
        if bad:
            print(json.dumps({"ok": False, "error": "synthetic_prompt_mismatch", "files": bad}))
            return 1
    else:
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for name, data in rendered.items():
            (args.output_dir / name).write_bytes(data)
    print(json.dumps({"ok": True, "checked": args.check, "source": "original integer synthesis",
                      "files": {name: digest(data) for name, data in rendered.items()}}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
